-- KrishiMitra Supabase / PostgreSQL Schema & Initial Seed Data
-- Database: PostgreSQL 14+ / Supabase

-- 1. Users
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  mobile VARCHAR(15) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) DEFAULT 'farmer' CHECK (role IN ('farmer', 'admin')),
  preferred_language VARCHAR(10) DEFAULT 'en',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Farmer Profiles
CREATE TABLE IF NOT EXISTS farmer_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT UNIQUE NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  village VARCHAR(100),
  district VARCHAR(100),
  state VARCHAR(100),
  land_size NUMERIC(10,2),
  land_unit VARCHAR(20) DEFAULT 'acres',
  soil_type VARCHAR(50),
  irrigation_available SMALLINT DEFAULT 0,
  irrigation_type VARCHAR(50),
  preferred_crops VARCHAR(255),
  latitude NUMERIC(10,6),
  longitude NUMERIC(10,6)
);

-- 3. Reference Crops
CREATE TABLE IF NOT EXISTS crops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  name_hi VARCHAR(100),
  category VARCHAR(50),
  avg_duration_days INT,
  stages JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Farmer Crops
CREATE TABLE IF NOT EXISTS farmer_crops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  crop_id BIGINT NOT NULL REFERENCES crops(id) ON DELETE CASCADE,
  variety VARCHAR(100),
  sowing_date DATE,
  field_size NUMERIC(10,2),
  field_unit VARCHAR(20) DEFAULT 'acres',
  status VARCHAR(20) DEFAULT 'active' CHECK (status IN ('active', 'harvested', 'cancelled')),
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Farming Activities Log
CREATE TABLE IF NOT EXISTS farming_activities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farmer_crop_id BIGINT NOT NULL REFERENCES farmer_crops(id) ON DELETE CASCADE,
  activity_type VARCHAR(50) NOT NULL,
  description TEXT,
  activity_date DATE NOT NULL,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Farming Calendar
CREATE TABLE IF NOT EXISTS farming_calendar (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farmer_crop_id BIGINT NOT NULL REFERENCES farmer_crops(id) ON DELETE CASCADE,
  activity_type VARCHAR(50) NOT NULL,
  title VARCHAR(200) NOT NULL,
  description TEXT,
  scheduled_date DATE NOT NULL,
  status VARCHAR(20) DEFAULT 'pending' CHECK (status IN ('pending', 'completed', 'skipped')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Notifications
CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  category VARCHAR(50) NOT NULL,
  title VARCHAR(255) NOT NULL,
  message TEXT,
  priority VARCHAR(20) DEFAULT 'normal' CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
  is_read SMALLINT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Assistant Conversations
CREATE TABLE IF NOT EXISTS assistant_conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(255),
  crop_id BIGINT REFERENCES crops(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Assistant Messages
CREATE TABLE IF NOT EXISTS assistant_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES assistant_conversations(id) ON DELETE CASCADE,
  role VARCHAR(20) NOT NULL CHECK (role IN ('user', 'assistant')),
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Disease Reports
CREATE TABLE IF NOT EXISTS disease_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  crop_id BIGINT REFERENCES crops(id) ON DELETE SET NULL,
  image_path VARCHAR(255),
  diagnosis VARCHAR(255),
  confidence VARCHAR(50),
  suggestions TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Soil Records
CREATE TABLE IF NOT EXISTS soil_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  soil_type VARCHAR(100),
  ph NUMERIC(4,2),
  nitrogen NUMERIC(8,2),
  phosphorus NUMERIC(8,2),
  potassium NUMERIC(8,2),
  organic_carbon NUMERIC(5,2),
  notes TEXT,
  test_date DATE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. Knowledge Articles
CREATE TABLE IF NOT EXISTS knowledge_articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category VARCHAR(100) NOT NULL,
  crop_id BIGINT REFERENCES crops(id) ON DELETE SET NULL,
  title VARCHAR(255) NOT NULL,
  title_hi VARCHAR(255),
  content TEXT NOT NULL,
  content_hi TEXT,
  source VARCHAR(255),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

